//! Differential harness for the aeneas-lean-checker vertical slice.
//!
//! Layout:
//!   - `ref_impl` / `model` — flat fixtures without crate-local ADTs
//!     (single hand-curated `model.rs` with `<crate>_<fn>_model`
//!     names; regen via `scripts/regen-diff-models.sh`).
//!   - `aggregates_basic` / `reborrows` — per-fixture modules for
//!     ADT fixtures (each carries its own `struct Pair` decl, so
//!     they cannot share the flat namespace).
//!
//! Proptests in `tests/diff.rs` compare R₀ (the original Rust source,
//! copied verbatim from `tests/src/*.rs`) against R₁ (the
//! `aeneas-check --rust-model` output) on randomised inputs.

/// Reference implementations (R₀) copied verbatim from
/// `tests/src/*.rs`. `&mut` signatures are reshaped to forward
/// scalars to match the cert convention.
pub mod ref_impl {
    // ---- incr_cert.rs ----

    /// `pub fn incr(x: &mut u32) { *x += 1; }` reshaped to
    /// `u32 → u32`. Release-mode `+` wraps silently.
    pub fn incr_cert_incr(x: u32) -> u32 {
        x.wrapping_add(1)
    }

    // ---- constants.rs ----

    pub const fn constants_incr(n: u32) -> u32 {
        n.wrapping_add(1)
    }

    pub const fn constants_mk_pair0(x: u32, y: u32) -> (u32, u32) {
        (x, y)
    }

    pub const fn constants_add(a: i32, b: i32) -> i32 {
        a.wrapping_add(b)
    }

    // ---- bitwise.rs ----

    pub fn bitwise_xor_u32(a: u32, b: u32) -> u32 {
        a ^ b
    }

    pub fn bitwise_or_u32(a: u32, b: u32) -> u32 {
        a | b
    }

    pub fn bitwise_and_u32(a: u32, b: u32) -> u32 {
        a & b
    }

    pub fn bitwise_shift_u32(a: u32) -> u32 {
        let i: usize = 16;
        let mut t = a >> i;
        t <<= i;
        t
    }

    pub fn bitwise_shift_i32(a: i32) -> i32 {
        let i: isize = 16;
        let mut t = a >> i;
        t <<= i;
        t
    }

    // ---- compare_simple.rs ----

    pub fn compare_simple_id_u32(x: u32) -> u32 {
        x
    }

    pub fn compare_simple_add_u32(a: u32, b: u32) -> u32 {
        a.wrapping_add(b)
    }

    // ---- calls.rs ----

    /// `pub fn incr_inner(y: &mut u32)` reshaped to `u32 → u32` per
    /// the cert convention (forward collapses `&mut` borrow).
    pub fn calls_incr_inner(y: u32) -> u32 {
        y.wrapping_add(1)
    }

    /// `pub fn pick(b: bool, x: u32, y: u32) -> u32`.
    pub fn calls_pick(b: bool, x: u32, y: u32) -> u32 {
        let mut r = 0u32;
        if b {
            r = x;
        } else {
            r = y;
        }
        r.wrapping_add(1)
    }
}

