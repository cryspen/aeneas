// ----------------------------------------------------------------------
// Phase 1C: ADT fixtures — per-fixture modules with their own struct
// decls. Each crate's `Pair` etc. is module-local to avoid name
// collisions with other fixtures' homonyms.
// ----------------------------------------------------------------------

pub mod aggregates_basic {
    #![allow(unused_variables, dead_code, unused_parens, unused_mut, non_snake_case)]

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub struct Pair {
        pub x: u32,
        pub y: u32,
    }

    pub fn mk_pair_ref(x: u32, y: u32) -> Pair {
        Pair { x, y }
    }

    pub fn mk_tuple_ref(x: u32, y: u32) -> (u32, u32) {
        (x, y)
    }

    include!("aggregates_basic_model.rs");
}

pub mod reborrows {
    #![allow(unused_variables, dead_code, unused_parens, unused_mut, non_snake_case)]

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    pub struct Pair {
        pub fst: u32,
        pub snd: u32,
    }

    pub fn set_fst_ref(p: Pair, v: u32) -> Pair {
        let mut p = p;
        p.fst = v;
        p
    }

    // Phase 1C: copy of `set_fst_model` emitted by aeneas-check from
    // tests/llbc/reborrows.cert.json. The sibling `set_idx_model` in
    // the same generated file emits `Array.update(x1, x2, x3)` (a
    // separate emitter gap), so we hand-copy just this one fn here
    // instead of `include!`ing the whole file.
    pub fn set_fst_model(x1: Pair, x2: u32) -> Pair {
        Pair { fst: x2, ..x1 }
    }
}

