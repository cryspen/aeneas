def main() -> int:
    parser = argparse.ArgumentParser(description=f"Rename `{OLD}` into `{NEW}`.")
    parser.add_argument(
        "--root",
        default=os.getcwd(),
        help="aeneas checkout to rewrite (default: the current directory)",
    )
    parser.add_argument(
        "--check", action="store_true", help="report what would change, write nothing"
    )
    parser.add_argument(
        "--audit",
        action="store_true",
        help="list the `Result` tokens left in the tree and exit",
    )
    parser.add_argument(
        "--self-test",
        action="store_true",
        help="check the rewriting rules against known inputs and exit",
    )
    args = parser.parse_args()

    if args.self_test:
        return self_test()

    root = os.path.abspath(args.root)
    if not os.path.isdir(os.path.join(root, "backends", "lean")):
        print(f"error: {root} does not look like the aeneas repository", file=sys.stderr)
        return 2

    if args.audit:
        audit(root)
        return 0

    ocaml_changed, errors = apply_ocaml(root, args.check)
    token_changed = apply_tokens(root, args.check)
    # The re-wrapping rules match post-rename text, so they only make sense once
    # the token rewrite has been written to disk.
    if args.check:
        reflow_changed, warnings = 0, []
    else:
        reflow_changed, warnings = apply_reflow(root, args.check)

    verb = "would change" if args.check else "changed"
    print(f"{verb} {token_changed} Lean/Markdown file(s)")
    print(f"{verb} {ocaml_changed} OCaml file(s)")
    print(f"{verb} {reflow_changed} file(s) by re-wrapping `#guard_msgs` output")

    if not args.check:
        print(
            "\nnext, in order — both are checked by CI:\n"
            "  1. `make test`. `tests/lean` is GENERATED. This script only"
            f" renames it textually, which keeps the old line breaks: `{NEW}` is"
            f" shorter than `{OLD}`, so Aeneas' own pretty-printer now fits"
            " declarations that used to wrap. Only re-extraction produces the"
            " bytes CI compares against. Commit what it regenerates.\n"
            "  2. `make format`. ocamlformat (margin 80) re-wraps for the same"
            " reason. Commit what it changes, and add it to REFLOW_REPLACEMENTS"
            " so a fresh run reproduces this tree.\n"
            "Re-run this script after any merge: files the base branch added"
            " since the rename still say `Result`."
        )

    guards = count_guard_msgs(root)
    if guards:
        print(
            f"\nnote: {guards} `#guard_msgs` docstring(s) mention `{NEW}`. Their"
            " expected output is verbatim pretty-printer output, and"
            f" `{NEW}` is shorter than `{OLD}`, so Lean may re-wrap some of them."
            " `lake build` is the arbiter; add any new re-wrapping to"
            " REFLOW_REPLACEMENTS."
        )

    if warnings:
        print("\nwarnings:")
        for warning in warnings:
            print(f"  {warning}")
    if errors:
        print("\nerrors:", file=sys.stderr)
        for error in errors:
            print(f"  {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
