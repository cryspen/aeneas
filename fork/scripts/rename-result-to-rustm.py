#!/usr/bin/env python3
"""Rename the Lean error monad `Aeneas.Std.Result` into `Aeneas.Std.RustM`.

This is a mechanical, idempotent rewrite so that it can be re-applied on any
branch/fork (e.g. after a merge or a rebase onto upstream `main`) instead of
being redone by hand.

What it does
------------

1. Lean sources (`backends/lean`, `tests/lean`) and Markdown documentation
   (`documentation`) are rewritten token-wise: every *dotted identifier chain*
   (e.g. `Aeneas.Std.Result.ok`, `core::result::Result`) is parsed, and the
   components that denote the Aeneas error monad are renamed.

2. A handful of places in the OCaml compiler hard-code the Lean name of the
   monad. Those are handled by narrow regexes applied across `src/` (see
   `OCAML_RULES`), tight enough that OCaml's own `Result` module and the
   backend-independent `TResult`/`ToResult` constructors are never touched.

3. Because `RustM` is a character shorter than `Result`, some lines re-wrap.
   Continuation lines of a hanging `do` block are re-indented automatically;
   `#guard_msgs` docstrings, which quote Lean's pretty-printer verbatim, are
   patched by `REFLOW_REPLACEMENTS` and flagged for a `lake build` check.

What it deliberately does *not* touch
-------------------------------------

* `core.result.Result` / `core::result::Result` / `Aeneas.Std.Core.Result`:
  that is the translation of Rust's `core::result::Result`, a different type.
* Anything spelled with `::`, which is Rust path syntax, not Lean's — so
  `Result::branch` in a doc comment names Rust's method, not ours.
* An unqualified `Result` inside a declaration that lives under the
  `core.result` namespace: there Lean resolves it to Rust's type, and the monad
  has to be spelled `Std.Result` (which is renamed as usual).
* `Lean.Meta.Simp.Result` and friends (`Simp.Result`).
* Identifiers that merely *contain* `Result` but are unrelated:
  `PreprocessResult`, `CancelResult`, `computeCasesOnResultType`, `onResult`,
  `simpResult`, `rwResult`, `ResultType`, `Results`, ...
* The Coq / F* / HOL4 backends, which use a lowercase `result` type.

Usage
-----

The script is kept in `fork/scripts/` of the cryspen/aeneas fork. Point it at
a checkout with `--root` (or run it from one):

    rename-result-to-rustm.py --root path/to/aeneas   # rewrite in place
    rename-result-to-rustm.py --check                 # report, change nothing
    rename-result-to-rustm.py --audit                 # surviving `Result` tokens
    rename-result-to-rustm.py --self-test             # check the rules

Re-running the script on an already-renamed tree is a no-op.

The script is NOT the whole job. `tests/lean` is generated by the compiler, and
`RustM` being shorter than `Result` changes where Aeneas' pretty-printer and
ocamlformat break lines. After running this, run `make test` and `make format`
and commit what they change — CI compares against both. And re-run the script
after every merge: files the base branch added meanwhile still say `Result`.
"""

from __future__ import annotations

import argparse
import collections
import os
import re
import sys

# --------------------------------------------------------------------------
# Configuration
# --------------------------------------------------------------------------

OLD = "Result"
NEW = "RustM"

# Directories rewritten with the token-based rewriter, with the extensions we
# look at in each of them. Paths are relative to the repository root.
TOKEN_TREES: list[tuple[str, tuple[str, ...]]] = [
    ("backends/lean", (".lean",)),
    ("tests/lean", (".lean",)),
    ("documentation", (".md",)),
]

# Identifier components that must be renamed. Keys are *whole* components of a
# dotted chain (so `mapM_Result_length` is one component, not three).
COMPONENT_RENAMES: dict[str, str] = {
    "Result": "RustM",
    # Instances declared next to the inductive in `Std/Primitives.lean`.
    "Result_Inhabited": "RustM_Inhabited",
    "Result_Nonempty": "RustM_Nonempty",
    # Conversions and lemmas that mention the monad in their name.
    "ofResult": "ofRustM",
    "mapM_Result_length": "mapM_RustM_length",
    "mapM_Result_ok": "mapM_RustM_ok",
}

# If the component immediately preceding a `Result` component is one of these,
# the chain denotes something else and is left alone:
#   `core.result.Result`, `core::result::Result`  -> Rust's `Result`
#   `Aeneas.Std.Core.Result`                      -> ditto, fully qualified
#   `Simp.Result`, `Lean.Meta.Simp.Result`        -> Lean's simp results
PROTECTED_PREDECESSORS: frozenset[str] = frozenset({"result", "Core", "Simp"})

# Prose, where `Result` is the English word rather than the type. The monad is
# spelled `` `Result` `` in comments and documentation, and a backtick stops
# these patterns from matching, so they only ever fire on plain English:
#
#     /-- Result type of a `casesOn` whose minor is … -/     (Do/Elab.lean)
#     - **Result type annotation**: always annotate the result binder …
PROSE_EXCEPTIONS: list[str] = [
    r"\bResult\s+type\b",
]

# The namespace the monad is declared in. A `Result` declared anywhere else is a
# different type — `Aeneas.StepStar.Result` is a tactic's internal record — and
# inside its namespace an unqualified `Result` refers to *it*. Those namespaces
# are discovered by scanning the tree, so a fork that adds one is handled too.
#
# This matters more than it looks: renaming a local `Result` together with all
# its uses still compiles, so `lake build` does not catch the mistake.
MONAD_NAMESPACE = "Aeneas.Std"

# --- The OCaml compiler -----------------------------------------------------
#
# A few places in `src/` hard-code the Lean name of the monad. They are rewritten
# with regexes scoped tightly enough that OCaml's own `Result` module, and the
# backend-independent `TResult`/`ToResult` constructors, are never touched.
#
# Rules are applied to *every* `.ml`/`.mli` file under `src/` rather than to a
# fixed path: branches move between files and forks add new emission sites (the
# Cryspen fork, for instance, emits a second Lean header under `core_models_lib`).
# `min_count` is the number of matches expected across the whole tree; falling
# short is an error, so a refactor upstream is reported instead of silently
# dropping a rename.
OCamlRule = tuple[str, str, str, int, str]  # (pattern, repl, done, min, what)

OCAML_RULES: list[OCamlRule] = [
    # Every generated Lean file starts with the namespaces to open. There may be
    # several such headers (plain, `core_models_lib`, ...). The other backends'
    # headers (`Require Import`, `module`, `open primitivesLib`) never mention
    # `Result`, so anchoring on `"open ` keeps this Lean-only.
    (
        r'("open [^"\n]*?)\bResult\b',
        r"\1" + NEW,
        r'"open [^"\n]*?\b' + NEW + r"\b",
        1,
        "Lean `open` header",
    ),
    # The name of the monad in the Lean backend's table of builtin ADTs.
    # Coq/F*/HOL4 use a lowercase `result`, so this matches the Lean branch only.
    (
        r'\(TResult, "Result"\)',
        f'(TResult, "{NEW}")',
        r'\(TResult, "' + NEW + r'"\)',
        1,
        "Lean builtin ADT name",
    ),
    # Doc comment showing an example of generated Lean code.
    (
        r"\bdef CONST : Result u32\b",
        f"def CONST : {NEW} u32",
        r"\bdef CONST : " + NEW + r" u32\b",
        1,
        "doc comment example",
    ),
]

# --- Re-wrapping ------------------------------------------------------------
#
# `RustM` is one character shorter than `Result`, so anything that lays out code
# to a line width reflows: Lean's pretty-printer (quoted verbatim inside
# `#guard_msgs` docstrings) and ocamlformat (`margin = 80` in `src/.ocamlformat`)
# both do. These replacements are applied *after* the rename and are pure
# re-wrapping: no token changes.
#
# Unlike the rules above these are best-effort — what a formatter does depends on
# its version and on the surrounding code — so a rule that no longer applies is
# reported as a warning rather than an error. The tools are the arbiters:
# `lake build` for Lean, `make format` for OCaml. See the note printed at the end
# of a run.
#   (path, old, new, expected count)
REFLOW_REPLACEMENTS: list[tuple[str, str, str, int]] = [
    (
        "backends/lean/Aeneas/Command/Decompose/TestsBig.lean",
        "  U32 →\n"
        "    U32 →\n"
        "      U32 → RustM (UScalar UScalarTy.U32 × UScalar UScalarTy.U32"
        " × UScalar UScalarTy.U32 × UScalar UScalarTy.U32) :=\n",
        "  U32 →\n"
        "    U32 → U32 → RustM (UScalar UScalarTy.U32 × UScalar UScalarTy.U32"
        " × UScalar UScalarTy.U32 × UScalar UScalarTy.U32) :=\n",
        4,
    ),
    # The shorter name makes this `else` branch fit within ocamlformat's margin,
    # so it no longer wants it on a line of its own. CI runs `make format
    # --check`, so getting this wrong fails the build.
    (
        "src/Translate.ml",
        '      else\n'
        '        Printf.fprintf out "open Aeneas Aeneas.Std RustM'
        ' ControlFlow Error\\n";\n',
        '      else Printf.fprintf out "open Aeneas Aeneas.Std RustM'
        ' ControlFlow Error\\n";\n',
        1,
    ),
]

# --------------------------------------------------------------------------
# Token-based rewriting
# --------------------------------------------------------------------------

# A dotted identifier chain: `Foo.bar.baz`, `core::result::Result`, `Result`.
# We deliberately keep the component alphabet small (ASCII identifiers) since
# that is all the names we care about need; anything else simply terminates a
# chain, which is safe because we only ever rewrite whole components.
_COMPONENT = r"[A-Za-z_][A-Za-z0-9_']*"
IDENT_CHAIN_RE = re.compile(
    r"(?<![A-Za-z0-9_'])"  # do not start in the middle of an identifier
    r"(?<!\.)(?<!::)"  # do not start in the middle of a chain
    # (a *single* `:` is Lean's type ascription, as in `(m : Result α)`,
    #  so it must not prevent a match)
    rf"{_COMPONENT}(?:(?:\.|::){_COMPONENT})*"
)

SPLIT_RE = re.compile(r"(\.|::)")


def rename_chain(chain: str, protect_bare: bool = False) -> str:
    """Rewrite one dotted identifier chain, or return it unchanged.

    `protect_bare` leaves an unqualified `Result` alone; see `lean_scopes`.
    """
    parts = SPLIT_RE.split(chain)  # [comp, sep, comp, sep, comp, ...]
    # `::` is Rust path syntax, never Lean's. So a chain that uses it names a
    # Rust item (`Result::branch`, `core::result::Result`, ...), not ours.
    if "::" in parts[1::2]:
        return chain
    components = parts[0::2]
    out = list(parts)
    for i, component in enumerate(components):
        new = COMPONENT_RENAMES.get(component)
        if new is None:
            continue
        if i > 0 and components[i - 1] in PROTECTED_PREDECESSORS:
            continue
        if i == 0 and protect_bare and component == OLD:
            continue
        out[2 * i] = new
    return "".join(out)


PROSE_EXCEPTIONS_RE = re.compile("|".join(PROSE_EXCEPTIONS))


def rewrite_text(text: str, protect_bare: bool = False) -> str:
    keep = [m.span() for m in PROSE_EXCEPTIONS_RE.finditer(text)]

    def replace(match: re.Match[str]) -> str:
        start = match.start()
        if any(lo <= start < hi for lo, hi in keep):
            return match.group(0)
        return rename_chain(match.group(0), protect_bare)

    return IDENT_CHAIN_RE.sub(replace, text)


# --- Namespace-aware protection of unqualified `Result` ---------------------
#
# Inside a declaration that lives under the `core.result` namespace, Lean
# resolves an unqualified `Result` to `core.result.Result` — Rust's type — not
# to the monad. `Aeneas/Std/Core/Convert.lean` relies on that:
#
#     theorem core.result.Result.Insts.….from_residual.spec
#         … (r : Result convert.Infallible E) …
#
# The monad is always spelled `Std.Result` in those declarations (it has to be),
# and that form is still renamed; only the unqualified spelling is protected.
NAMESPACE_RE = re.compile(r"^\s*namespace\s+([A-Za-z_][A-Za-z0-9_.']*)")
END_RE = re.compile(r"^\s*end\s+([A-Za-z_][A-Za-z0-9_.']*)")
DECL_RE = re.compile(
    r"^\s*(?:@\[[^\]]*\]\s*)?"
    r"(?:private |protected |noncomputable |partial |unsafe |scoped )*"
    r"(?:def|theorem|lemma|abbrev|instance|inductive|structure|class|example)\b"
    r"(.*)$"
)
DECL_NAME_RE = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_.']*)")
RUST_RESULT_NS_RE = re.compile(r"(^|\.)core\.result(\.|$)")


LOCAL_RESULT_DECL_RE = re.compile(
    r"^\s*(?:@\[[^\]]*\]\s*)?"
    r"(?:private |protected |noncomputable |partial |unsafe |scoped )*"
    r"(?:structure|inductive|abbrev|def|class)\s+" + OLD + r"(?![\w.'])"
)


def local_result_namespaces(root: str) -> frozenset[str]:
    """Namespaces that declare their own `Result`, other than the monad's."""
    found: set[str] = set()
    for relpath in iter_files(root):
        if not relpath.endswith(".lean"):
            continue
        with open(os.path.join(root, relpath), encoding="utf-8") as f:
            stack: list[str] = []
            for line in f:
                namespace = NAMESPACE_RE.match(line)
                end = END_RE.match(line)
                if namespace:
                    stack.append(namespace.group(1))
                elif end:
                    if stack and stack[-1] == end.group(1):
                        stack.pop()
                elif LOCAL_RESULT_DECL_RE.match(line):
                    qualified = ".".join(stack)
                    if qualified != MONAD_NAMESPACE:
                        found.add(qualified)
    return frozenset(found)


def lean_scopes(lines: list[str], local: frozenset[str] = frozenset()) -> list[bool]:
    """For each line, whether an unqualified `Result` means some other type."""
    stack: list[str] = []
    decl: str | None = None
    awaiting_name = False
    scopes: list[bool] = []
    for line in lines:
        stripped = line.strip()
        namespace = NAMESPACE_RE.match(line)
        end = END_RE.match(line)
        if namespace:
            stack.append(namespace.group(1))
            decl, awaiting_name = None, False
        elif end:
            if stack and stack[-1] == end.group(1):
                stack.pop()
            decl, awaiting_name = None, False
        else:
            declaration = DECL_RE.match(line)
            if declaration:
                rest = declaration.group(1).strip()
                name = DECL_NAME_RE.match(rest) if rest else None
                if name:
                    decl, awaiting_name = name.group(1), False
                else:
                    # `theorem` on its own line, name on the next one.
                    decl, awaiting_name = None, not rest
            elif awaiting_name and stripped:
                name = DECL_NAME_RE.match(stripped)
                decl, awaiting_name = (name.group(1) if name else None), False
        namespaces = ".".join(stack)
        qualified = ".".join(stack + ([decl] if decl else []))
        # Rust's `Result`, reached through the `core.result` namespace…
        protect = bool(RUST_RESULT_NS_RE.search(qualified))
        # …or a type of the same name declared by the enclosing namespace.
        protect = protect or any(
            namespaces == n or namespaces.startswith(n + ".") for n in local
        )
        scopes.append(protect)
    return scopes


def rewrite_lean(text: str, local: frozenset[str] = frozenset()) -> str:
    lines = text.split("\n")
    scopes = lean_scopes(lines, local)
    return "\n".join(
        rewrite_text(line, protect) for line, protect in zip(lines, scopes)
    )


# A `do` that opens a block *and* carries its first statement on the same line.
# The statements that follow are aligned on the column right after `do `, e.g.
#
#     def Const_Test : Result Std.U32 := do let i ← 100#u32 + 10#u32
#                                           i + 1#u32
#
# `RustM` is shorter than `Result`, so the `do` body moves one column to the
# left and the continuation lines have to follow, or Lean reads them as a
# continuation of the previous statement instead of a new one.
HANGING_DO_RE = re.compile(r"\bdo (?=\S)")


def fix_hanging_indent(old_lines: list[str], new_lines: list[str]) -> list[str]:
    out = list(new_lines)
    for i, old_line in enumerate(old_lines):
        match = HANGING_DO_RE.search(old_line)
        if match is None:
            continue
        # The prefix ends on a space, so cutting there never splits an
        # identifier and the rewrite of the prefix is the prefix of the rewrite.
        body_column = match.end()
        shift = body_column - len(rewrite_text(old_line[:body_column]))
        if shift <= 0:
            continue
        for j in range(i + 1, len(out)):
            stripped = out[j].lstrip(" ")
            if not stripped or len(out[j]) - len(stripped) != body_column:
                break
            out[j] = " " * (body_column - shift) + stripped
    return out


