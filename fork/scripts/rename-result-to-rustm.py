OCAML_SELF_TEST_CASES: list[tuple[str, str | None]] = [
    # --- renamed --------------------------------------------------------
    (
        'Printf.fprintf out "open Aeneas Aeneas.Std Result ControlFlow Error\\n";',
        'Printf.fprintf out "open Aeneas Aeneas.Std RustM ControlFlow Error\\n";',
    ),
    (
        'Printf.fprintf out "open Result ControlFlow Error\\n"',
        'Printf.fprintf out "open RustM ControlFlow Error\\n"',
    ),
    ('(TResult, "Result");', '(TResult, "RustM");'),
    (
        "def CONST : Result u32 := ok CONST.val",
        "def CONST : RustM u32 := ok CONST.val",
    ),
    # --- left alone -----------------------------------------------------
    ('(TResult, "result");', None),  # Coq / F* / HOL4
    ('Printf.fprintf out "open Primitives\\n"', None),
    ('Printf.fprintf out "open primitivesLib divDefLib\\n"', None),
    ("| Result.Ok clauses -> clauses", None),  # OCaml's own Result module
    ("Result.get_ok (mk_scalar min_ptr_size int_ty value)", None),
    ('| TResult -> "Result"', None),  # Pure-IR pretty-printer
    ('"@Result::Ok"', None),
    ('mk_type "core::result::Result" "core.result.Result"', None),
    ("| ToResult -> \"@toResult\"", None),
]


def apply_ocaml_rules_to_text(text: str) -> str:
    for pattern, repl, _done, _min_count, _what in OCAML_RULES:
        text = re.sub(pattern, repl, text)
    return text


def self_test() -> int:
    failures = 0
    for source, expected in SELF_TEST_CASES:
        want = source if expected is None else expected
        got = rewrite_text(source)
        if got != want:
            failures += 1
            print(f"FAIL\n  input:    {source}\n  expected: {want}\n  got:      {got}")
    for source, expected in LEAN_SCOPE_TEST_CASES:
        want = source if expected is None else expected
        got = rewrite_lean(source)
        if got != want:
            failures += 1
            print(f"FAIL (scope)\n  input:\n{source}\n  expected:\n{want}\n  got:\n{got}")
    for source, local, expected in LOCAL_RESULT_TEST_CASES:
        want = source if expected is None else expected
        got = rewrite_lean(source, local)
        if got != want:
            failures += 1
            print(f"FAIL (local)\n  input:\n{source}\n  expected:\n{want}\n  got:\n{got}")
    for source, expected in OCAML_SELF_TEST_CASES:
        want = source if expected is None else expected
        got = apply_ocaml_rules_to_text(source)
        if got != want:
            failures += 1
            print(f"FAIL (ocaml)\n  input:    {source}\n  expected: {want}\n  got:      {got}")
    total = (
        len(SELF_TEST_CASES)
        + len(LEAN_SCOPE_TEST_CASES)
        + len(LOCAL_RESULT_TEST_CASES)
        + len(OCAML_SELF_TEST_CASES)
    )
    if failures:
        print(f"self-test: {failures}/{total} case(s) failed")
        return 1
    print(f"self-test: {total}/{total} case(s) passed")
    return 0


