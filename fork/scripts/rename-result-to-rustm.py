WORD_RE = re.compile(r"[A-Za-z0-9_':.]*Result[A-Za-z0-9_':.]*")


GUARD_MSGS_RE = re.compile(r"/--(?:(?!-/).)*?\b" + NEW + r"\b(?:(?!-/).)*?-/\s*\n#guard_msgs", re.S)


def count_guard_msgs(root: str) -> int:
    """How many `#guard_msgs` docstrings mention the renamed monad."""
    total = 0
    for relpath in iter_files(root):
        if not relpath.endswith(".lean"):
            continue
        with open(os.path.join(root, relpath), encoding="utf-8") as f:
            total += len(GUARD_MSGS_RE.findall(f.read()))
    return total


def audit(root: str) -> None:
    """List every surviving `Result`-ish token in the rewritten trees.

    Everything printed here must be something we intentionally keep (Rust's
    `Result`, `Simp.Result`, unrelated names, ...).
    """
    counts: collections.Counter[str] = collections.Counter()
    where: dict[str, str] = {}
    for relpath in iter_files(root):
        with open(os.path.join(root, relpath), encoding="utf-8") as f:
            for lineno, line in enumerate(f, 1):
                for match in WORD_RE.findall(line):
                    counts[match] += 1
                    where.setdefault(match, f"{relpath}:{lineno}")
    if not counts:
        print("audit: no `Result` token left")
        return
    print("audit: surviving `Result` tokens (all of these should be expected):")
    for token, count in counts.most_common():
        print(f"  {count:5d}  {token:<40} e.g. {where[token]}")

    # The OCaml side is rewritten by a handful of narrow rules, so list every
    # string literal in `src/` that still mentions `Result`: anything that is a
    # piece of *Lean* syntax rather than Pure-IR printing needs a rule.
    print("\naudit: `Result` inside string literals in src/ (Lean syntax needs a rule):")
    for relpath in iter_ocaml_files(root):
        with open(os.path.join(root, relpath), encoding="utf-8") as f:
            for lineno, line in enumerate(f, 1):
                for literal in re.findall(r'"[^"\n]*"', line):
                    if "Result" in literal:
                        print(f"  {relpath}:{lineno}  {literal}")


