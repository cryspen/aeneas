# Driving the rewrite over the repository
# --------------------------------------------------------------------------


def iter_files(root: str) -> list[str]:
    """All files covered by the token-based rewriter, as relative paths."""
    files: list[str] = []
    for tree, extensions in TOKEN_TREES:
        base = os.path.join(root, tree)
        if not os.path.isdir(base):
            continue
        for dirpath, dirnames, filenames in os.walk(base):
            # Never descend into build artefacts or into symlinked trees (the
            # skill files are symlinked into `.claude/` and `.github/`).
            dirnames[:] = sorted(
                d
                for d in dirnames
                if d not in {".lake", ".git", "_build"}
                and not os.path.islink(os.path.join(dirpath, d))
            )
            for name in sorted(filenames):
                path = os.path.join(dirpath, name)
                if os.path.islink(path):
                    continue
                if name.endswith(extensions):
                    files.append(os.path.relpath(path, root))
    return files


def iter_ocaml_files(root: str) -> list[str]:
    """Every OCaml source under `src/`, skipping build output and symlinks."""
    files: list[str] = []
    base = os.path.join(root, "src")
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(
            d
            for d in dirnames
            if d not in {"_build", ".git"}
            and not os.path.islink(os.path.join(dirpath, d))
        )
        for name in sorted(filenames):
            if name.endswith((".ml", ".mli")):
                files.append(os.path.relpath(os.path.join(dirpath, name), root))
    return files


def apply_ocaml(root: str, check: bool) -> tuple[int, list[str]]:
    """Apply `OCAML_RULES` across `src/`. Returns (#files changed, errors)."""
    errors: list[str] = []
    texts = {rel: open(os.path.join(root, rel), encoding="utf-8").read() for rel in iter_ocaml_files(root)}
    originals = dict(texts)

    for pattern, repl, done, min_count, what in OCAML_RULES:
        applied = already = 0
        for rel, text in texts.items():
            new_text, n = re.subn(pattern, repl, text)
            applied += n
            if n:
                texts[rel] = new_text
            # A previous run may have done the work already.
            already += len(re.findall(done, texts[rel]))
        if applied + already < min_count:
            errors.append(
                f"src/: {what}: expected at least {min_count} match(es) of "
                f"{pattern!r}, found {applied} (and {already} already renamed)"
            )

    changed = 0
    for rel, text in texts.items():
        if text == originals[rel]:
            continue
        changed += 1
        if not check:
            with open(os.path.join(root, rel), "w", encoding="utf-8") as f:
                f.write(text)
    return changed, errors


def apply_reflow(root: str, check: bool) -> tuple[int, list[str]]:
    """Apply `REFLOW_REPLACEMENTS`. Returns (#files changed, warnings)."""
    warnings: list[str] = []
    edits: dict[str, str] = {}
    for relpath, old, new, expected in REFLOW_REPLACEMENTS:
        path = os.path.join(root, relpath)
        if not os.path.isfile(path):
            warnings.append(f"{relpath}: missing file, re-wrapping skipped")
            continue
        text = edits.get(relpath)
        if text is None:
            with open(path, encoding="utf-8") as f:
                text = f.read()
        count = text.count(old)
        if count != expected:
            # Already applied by an earlier run? Then nothing to do.
            if count == 0 and text.count(new) >= expected:
                continue
            tool = "make format" if relpath.startswith("src/") else "lake build"
            warnings.append(
                f"{relpath}: expected {expected} block(s) to re-wrap, found"
                f" {count} — this branch may not exist here; `{tool}` decides"
            )
            if count == 0:
                continue
        edits[relpath] = text.replace(old, new)

    changed = 0
    for relpath, text in edits.items():
        path = os.path.join(root, relpath)
        with open(path, encoding="utf-8") as f:
            if f.read() == text:
                continue
        changed += 1
        if not check:
            with open(path, "w", encoding="utf-8") as f:
                f.write(text)
    return changed, warnings


def apply_tokens(root: str, check: bool) -> int:
    changed = 0
    local = local_result_namespaces(root)
    for relpath in iter_files(root):
        path = os.path.join(root, relpath)
        with open(path, encoding="utf-8") as f:
            text = f.read()
        is_lean = relpath.endswith(".lean")
        new_text = rewrite_lean(text, local) if is_lean else rewrite_text(text)
        if new_text == text:
            continue
        if is_lean:
            new_text = "\n".join(
                fix_hanging_indent(text.split("\n"), new_text.split("\n"))
            )
        changed += 1
        if not check:
            with open(path, "w", encoding="utf-8") as f:
                f.write(new_text)
    return changed


